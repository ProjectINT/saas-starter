// Writes core/tenancy/permissions.generated.ts from public.role_permissions in
// the running local database (`npm run db:types` calls it after the type
// generation). Permission names in TS then cannot drift from the matrix that
// RLS and the RPCs check; which role holds which permission is still read at
// runtime, never compiled in.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const OUTPUT = "core/tenancy/permissions.generated.ts";

let status;

try {
  status = JSON.parse(execFileSync("npx", ["supabase", "status", "-o", "json"], { encoding: "utf8" }));
} catch {
  console.error("Local Supabase is not running. Start it with `npm run db:start`.");
  process.exit(1);
}

const response = await fetch(`${status.API_URL}/rest/v1/role_permissions?select=permission`, {
  headers: { apikey: status.SECRET_KEY },
});

if (!response.ok) {
  console.error(`Reading public.role_permissions failed: ${response.status} ${await response.text()}`);
  process.exit(1);
}

const rows = await response.json();
const permissions = [...new Set(rows.map((row) => row.permission))].sort();

const source = `// Generated by scripts/gen-permissions.mjs from public.role_permissions.
// Do not edit: grant permissions in a migration, then run \`npm run db:types\`.

export const PERMISSIONS = [
${permissions.map((permission) => `  "${permission}",`).join("\n")}
] as const;

export type Permission = (typeof PERMISSIONS)[number];
`;

writeFileSync(OUTPUT, source);
console.log(`Wrote ${permissions.length} permissions to ${OUTPUT}`);
